-- 0018: worker проверяет, что адресат предупреждения — действующий участник
--
-- Проблема. Задание «срок назначения скоро истечёт» шлёт предупреждение автору
-- назначения (`assignments.created_by`). Если membership автора отозван,
-- ManagerGuard ответит ему 404 на любой маршрут уведомлений: строка в
-- core.notifications создалась бы, но прочитать её было бы уже некому. Такие
-- записи копятся, а событие фактически никого не уведомляет. Продюсер в API
-- (notifyReviewers) действующий membership проверяет — worker не мог.
--
-- Решение. Колоночные привилегии на core.memberships: worker видит, кто состоит
-- в организации и в каком состоянии, и ничего больше. `permissions`, `role`,
-- `invited_by` и идентификаторы приглашавших ему недоступны — решение о правах
-- принимает API, фоновой обработке нужен только факт действующего членства.
-- Чтение остаётся в границах RLS: политика core.memberships требует
-- организацию в контексте транзакции, и обход идёт по организациям с withTenant.
grant select (id, organization_id, user_id, status) on core.memberships to context_worker;

comment on column core.memberships.status is
  'Состояние членства. Фоновые задания читают его, чтобы не создавать уведомления адресатам с отозванным доступом.';
