-- 0017: worker получает право закрывать сессии участника по истёкшему сроку
-- и читать уведомления не получает.
--
-- Проблема. Задание «срок назначения истёк» (apps/worker) переводит назначение
-- в состояние `expired` и одновременно отзывает открытую сессию участника,
-- иначе истёкшая ссылка продолжала бы работать до конца idle-срока. Права на
-- core.participant_sessions у роли `context_worker` при этом не было: в 0008
-- ей выдан рабочий минимум по ответам и заключениям.
--
-- Решение. Колоночные привилегии вместо табличных: worker видит только то, по
-- чему ищет сессию, и меняет только признак отзыва. `session_hash`,
-- `invitation_id` и сроки ему недоступны — секрет сессии участника фоновой
-- обработке не нужен ни в каком виде (ТЗ 10.5, 07.10).
grant select (id, organization_id, assignment_id, revoked_at)
  on core.participant_sessions to context_worker;
grant update (revoked_at)
  on core.participant_sessions to context_worker;

-- Уведомления worker по-прежнему только создаёт: чтение чужого ящика фоновой
-- обработке не нужно, а дедупликацию обеспечивает уникальный индекс
-- `notifications (recipient_user_id, event_key)` через ON CONFLICT DO NOTHING.
comment on table core.notifications is
  'Входящие уведомления кабинета. Только факт события и ссылка на ресурс: содержание заключения и свободный текст запросов сюда не попадают (ТЗ 01.7).';
