-- 0019: ссылка уведомления на ресурс ограничена схемой
--
-- Проблема. У `core.notifications.type` список значений закрыт check-constraint,
-- и чтение уведомления неизвестного типа честно падает как расхождение схемы и
-- кода. У `resource_type` такого ограничения не было: любая строка продюсера
-- проходила в базу, а чтение молча отдавало наружу `resource_id` без типа.
-- Клиент получал идентификатор, вести по которому некуда, а открытие такого
-- уведомления отвечало «страницы нет, ничего не удалено и доступ не отозван» —
-- утверждение о ресурсе, существование которого никто не проверял.
--
-- Решение. Список типов ресурса закрыт так же, как список типов события, и
-- дополнен `access_grant` (обращение за временным доступом, M13/M14). Вторая
-- проверка связывает пару: либо уведомление ссылается на ресурс и знает его
-- тип, либо не ссылается вовсе. Промежуточного состояния «id без типа» в базе
-- больше нет, и API может обращаться с нераспознанным значением строго.
--
-- Совместимость: обе проверки добавляются к существующим строкам без изменения
-- данных — на момент миграции все уведомления ссылаются на заключение и имеют
-- обе колонки заполненными.

alter table core.notifications
  add constraint notifications_resource_type_check
  check (resource_type is null
         or resource_type in ('report', 'assignment', 'access_grant'));

alter table core.notifications
  add constraint notifications_resource_pair_check
  check ((resource_type is null) = (resource_id is null));

comment on column core.notifications.resource_type is
  'Тип ресурса уведомления. Список закрыт: нераспознанное значение — расхождение схемы и кода, а не ввод пользователя.';
